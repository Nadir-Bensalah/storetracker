// ARCEP fiction ranges, by regional prefix.
const fictionPrefixes: Record<string, string> = {
  '1': '01 99 00',
  '2': '02 61 91',
  '3': '03 53 01',
  '4': '04 65 71',
  '5': '05 36 49',
};

function regionalPrefix(postalCode: string) {
  const department = Number(postalCode.slice(0, 2));
  if ([75, 77, 78, 91, 92, 93, 94, 95].includes(department)) return '1';
  if ([14, 22, 29, 35, 37, 44, 49, 50, 53, 56, 61, 72, 76, 85].includes(department)) return '2';
  if ([21, 51, 54, 57, 59, 62, 67, 68, 80].includes(department)) return '3';
  if ([1, 5, 6, 13, 26, 34, 38, 69, 73, 74, 83, 84].includes(department)) return '4';
  return '5';
}

function fictionalPhone(postalCode: string, index: number) {
  const suffix = String((index * 7919) % 10000).padStart(4, '0');
  return `${fictionPrefixes[regionalPrefix(postalCode)]} ${suffix.slice(0, 2)} ${suffix.slice(2)}`;
}

export const stores: Store[] = sites.map(
  ([brandId, area, street, postalCode, city, latitude, longitude, transit, overrides], index) => {
    const brand = brands[brandId];
    return {
      id: String(index + 1),
      brandId,
      name: `${brand.name} ${area}`,
      street,
      postalCode,
      city,
      coordinates: { latitude, longitude },
      phone: fictionalPhone(postalCode, index + 1),
      timeZone: 'Europe/Paris',
      hours: overrides?.hours ?? brand.hours,
      services: brand.services,
      transit: transit ? { mode: transit[0], station: transit[1] } : undefined,
      photos: overrides?.photos ?? brand.photos,
    };
  },
);
